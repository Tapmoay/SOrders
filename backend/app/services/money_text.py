"""金额**给人看**的写法（显示口径）—— 与"金额的值"是两件事。

## 规则（用户 2026-09-22 定的，三端同一条）

    先按分四舍五入（与全项目同一个进位），**再去掉末尾多余的 0**：
    `56.70 → "56.7"`、`87.00 → "87"`、`0.50 → "0.5"`

    ⛔ 只动**末尾的 0**，绝不近似：`56.77 → "56.77"`（"去掉多余的 0" ≠ "把 7 约掉"）。

用户原话：「把所有的那个关于金钱的那个显示…有零的全省…如果是 56.7 啊，就直接这样子，
不要 56.70…包括 87…不要写 87.00 了…但是如果账单是 56.77…是必须要有的，它不能直接把七给约掉了」。

## ⛔ 什么时候**不许**用它

这里是"**印给人看的字**"。下面这些是"**值**"，一位都不许动 ——
混一次的后果与「编辑价框误用 `formatMoney`」是同一类（用户没改价、价却变了）：

1. **接口出参**（`Decimal` 字段、`suppliers._money` 那种两位小数字符串）：
   客户端还会再过一次自己的显示口径；`backend/tests/test_supplier_payables.py` 等逐条钉着 `"1200.50"`。
2. **任何拿来做判据的字符串**：如"这次核销的金额必须等于所选订单合计"。
3. **通知 payload 里的结构化金额**（客户端要按它做算术/对账）——只有**正文那句话**才用本函数。
4. **要存回库里/回给模型的参数**。

## 为什么要有这个模块（而不是各处自己拼一遍"两位小数"）

改之前，后端有 5 处各写了一遍"给用户看的金额"：`driver_pay.describe()`、
`driver_billing_rules` 的价目摘要、价格变更通知正文、`message_center` 的退货退款文案、
`shipper_ledger` 那句 400 文案。其中 4 处印成 `¥62.00` 这种机器味，1 处（`_plain`，只管百分比）
已经去零 —— 同一屏上两种写法，用户会以为是两件事。进位仍然只有 `order_money.q2` 一处，
本模块**不重写进位**，只在它之后删掉末尾多余的 0。
"""

from app.services.order_money import q2

__all__ = ["money_text"]


def money_text(v) -> str:
    """金额 → **给人看**的字符串（去尾零）。`None` / 空串 → `"0"`（不抛）。

    非数值（`"abc"`、对象…）会**抛**而不是印成 `"0"`：那是编程错误，
    静默印个 0 会让"钱算错"看起来像"这笔是零"（本项目最贵的一类 bug）。
    """
    if v is None or v == "":
        return "0"
    s = str(q2(v))
    if "." in s:
        s = s.rstrip("0").rstrip(".")
    # `-0.001` 会印成 `-0`：负零不是钱，摆正（否则界面上出现「¥-0」）—— 与安卓/H5 两份同一条。
    return "0" if s in ("", "-0") else s
