#: v2 生效点：标题里写着这句话的那条提交。⛔ 改这句话 = 移动生效点，得先想清楚。
V2_MARKER = "Milestone Tag Grammar v2"

#: 里程碑编号：`R<3-9>-<两位数字>`，且必须独立成词。
#: · 前置否定环视 `(?<![0-9A-Za-z])` —— 别把 `XR4-01` 之类当成命中；
#: · 后置否定环视 `(?![0-9])` —— `R4-100` **不算**命中（它是把编号打多了一位，
#:   而 v1 的写法会让它因为子串 `R4-10` 而**假绿**，那是这一版专门补上的一条）。
MILESTONE_TAG = re.compile(r"(?<![0-9A-Za-z])R[3-9]-[0-9]{2}(?![0-9])")

#: **v3（2026-09-27 晚）**：日常开发改用四种事项 ID（用户交来的《开发规范 v1.0》§一）。
#:
#: ⛔ **这不是放宽** —— 它是**换标准**：R<轮次>-<nn> 是"整改阶段"的编号法，
#:   规范 §一 明确「R4-xx 属于架构整改 / 治理阶段历史，日常开发使用四种 ID」。
#:   两种形状**都要能回溯到一件事**，没有第三种（"什么都不写"仍然不合法）。
#:   用户对上一版（v2）的原话同样适用于这一版：
#:   「**不能只改正则**……扩展编号容量**不能削弱**『每个提交必须有明确位置』的治理。」
ITEM_TAG = re.compile(r"(?<![0-9A-Za-z])(?:FEAT|CHG|BUG|GOV)-[0-9]{4}(?![0-9])")

#: R3 **窗口内**的提交只许用本轮的编号（R3-xx）。窗口已经收口，但这条判据还在守着历史。
R3_WINDOW_TAG = re.compile(r"(?<![0-9A-Za-z])R3-[0-9]{2}(?![0-9])")

