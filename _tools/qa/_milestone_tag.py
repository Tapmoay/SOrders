# -*- coding: utf-8 -*-
r"""里程碑编号语法 **v2**（用户 2026-09-27 拍板）—— 全仓库**只有这一处定义**。

## v1 哪里不够用

v1 是 `R[3-9]-0\d` —— 它把"**每一轮只能有 10 个里程碑**"写死进了正则。
而 `R4-PROD-INTEGRATION` 开工之前，`R4-00`…`R4-09` 就已经用完：
R4-00…R4-08 是结构整改的九个里程碑，R4-09 是治理收口。**约束和现实冲突了。**

## v2：`R<轮次 3-9>-<两位数字>`，也就是 `R4-00` … `R4-99`

⛔ **为什么不用 R5-0x 顶着**：**里程碑编号不是轮次**。这一阶段仍然是 R4 的后半段
（`R4-PROD-INTEGRATION`），把它写成 R5 会让以后读历史的人问
「为什么 R5 又在做 R4 的生产接线？」—— 实际上没有新主题。

⛔ **为什么不允许一串提交共用同一个编号**（v1 时代 `R4-09` 被四条提交用过）：
**提交标签本身就是施工账本的索引**。同一个编号用四次之后，你必须再读 commit message 的
后半句才知道这条到底是 P0 / P1 / 迁移 / Shadow / Canary —— 标签就不再是索引了。

## 三条规矩

| # | 规矩 | 判据 |
| --- | --- | --- |
| 1 | **形状**：`R<3-9>-<两位数字>`，而且这个记号必须**独立成词** | `R4-10` 合法 / `R4-100` 不合法（后面还跟着数字，是打错了）/ `R4-A0` 不合法 / `R10-01` 不合法 |
| 2 | **每条提交都要有**（R3 收口之后的长期纪律，v1 就有） | `_check_r3_constraints.py::probe_commit_milestone_tag` |
| 3 | **不许重号**：v2 生效之后，每条提交的编号必须**唯一** | 同上（见 `duplicate_tags`） |

⚠️ 第 3 条**不翻旧账**：v2 生效之前的 R4-00…R4-09 确实一条编号配多条提交 —— 那是 v1 时代的事，
判据只从 v2 生效那一刻起要求唯一（生效点 = 标题里写着 `Milestone Tag Grammar v2` 的那条提交）。

⚠️ 用户 2026-09-27 的原话（为什么这次要把它当成一次正式治理变更，而不是偷偷改正则）：

> 「**不能只改正则。** 否则你自己前面抓到的『治理规则绕过去了』问题又会回来。
>  这次应该把它作为一个正式的小治理变更：Milestone Tag Grammar v2。」
> 「扩展编号容量**不能削弱**『每个提交必须有明确位置』的治理。」
"""
from __future__ import annotations

import re

#: v2 生效点：标题里写着这句话的那条提交。⛔ 改这句话 = 移动生效点，得先想清楚。
V2_MARKER = "Milestone Tag Grammar v2"

#: 里程碑编号：`R<3-9>-<两位数字>`，且必须独立成词。
#: · 前置否定环视 `(?<![0-9A-Za-z])` —— 别把 `XR4-01` 之类当成命中；
#: · 后置否定环视 `(?![0-9])` —— `R4-100` **不算**命中（它是把编号打多了一位，
#:   而 v1 的写法会让它因为子串 `R4-10` 而**假绿**，那是这一版专门补上的一条）。
MILESTONE_TAG = re.compile(r"(?<![0-9A-Za-z])R[3-9]-[0-9]{2}(?![0-9])")

#: R3 **窗口内**的提交只许用本轮的编号（R3-xx）。窗口已经收口，但这条判据还在守着历史。
R3_WINDOW_TAG = re.compile(r"(?<![0-9A-Za-z])R3-[0-9]{2}(?![0-9])")


def milestone_tag_of(subject: str) -> str:
    """提交标题 → 里程碑编号（取不到就返回空串）。

    ⛔ 只认**第一个**命中：标题里写两个编号（例如 "R4-10 修 R4-09 的洞"）时，
    第一个才是这条提交自己的位置。
    """
    m = MILESTONE_TAG.search(subject or "")
    return m.group(0) if m else ""


def duplicate_tags(rows: list[tuple[str, str]]) -> list[str]:
    """`[(短哈希, 标题)]` → **被判据看到的编号里重号的那些**（去重后按编号排序）。

    ⚠️ 只有取得到编号的行参与判重：取不到编号的那些由第 2 条规矩单独管
    （"没有编号"和"编号重复"是两件事，报错文案也必须分开）。
    """
    seen: dict[str, int] = {}
    for _h, subject in rows:
        tag = milestone_tag_of(subject)
        if tag:
            seen[tag] = seen.get(tag, 0) + 1
    return sorted(t for t, n in seen.items() if n > 1)
