def milestone_tag_of(subject: str) -> str:
    """提交标题 → 里程碑编号（取不到就返回空串）。

    ⛔ 只认**第一个**命中：标题里写两个编号（例如 "R4-10 修 R4-09 的洞"）时，
    第一个才是这条提交自己的位置。
    """
    s = subject or ""
    m = MILESTONE_TAG.search(s)
    if m:
        return m.group(0)
    m = ITEM_TAG.search(s)
    return m.group(0) if m else ""


def duplicate_tags(rows: list[tuple[str, str]]) -> list[str]:
    """`[(短哈希, 标题)]` → **被判据看到的编号里重号的那些**（去重后按编号排序）。

    ⚠️ 只有取得到编号的行参与判重：取不到编号的那些由第 2 条规矩单独管
    （"没有编号"和"编号重复"是两件事，报错文案也必须分开）。

    ⚠️ **v3（2026-09-27 晚）：只对「里程碑编号」判重号，事项 ID 不判。**

    · @@BT@@R<轮次>-<nn>@@BT@@ 是**里程碑** —— 一个里程碑一条提交，重号就说明标签不再是索引（v2 的理由，原样保留）；
    · @@BT@@FEAT/CHG/BUG/GOV-xxxx@@BT@@ 是**事项** —— 一个事项**本来就会有多条提交**
      （实现 / 修补 / 关闭，实测：@@BT@@FEAT-0003@@BT@@ 就有一条"实现"一条"关闭"）。
      对事项 ID 判重号会逼着人**把 ID 写错或漏写**，那才是真的削弱可回溯性。
      事项的可回溯性来自"**一组**提交指向同一个事项"，这正是"事项"该有的形状。
    """
    seen: dict[str, int] = {}
    for _h, subject in rows:
        m = MILESTONE_TAG.search(subject or "")
        if m:
            seen[m.group(0)] = seen.get(m.group(0), 0) + 1
    return sorted(t for t, n in seen.items() if n > 1)
