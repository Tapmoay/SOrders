package com.tapmoay.sorders.ai

/**
 * 「卡已发」这句话的**结构化兜底**。
 *
 * ### 为什么要用代码管住一句话
 * 真机实测**两次**（2026-09-16 / 同日 v3.24）出现同一种情况：
 * 用户说「新增挂账单位 X，再登记一辆车 Y」，模型只调了两次**只读**工具，
 * 然后回复「两张确认卡发给你了……各点一下「确认」才生效」。
 * **屏幕上没有卡**——用户会去找一张不存在的卡，然后卡死（不知道该说什么）。
 *
 * 第一次之后已经加过提示词（「这句话只能在你刚刚真的调用过 preview_write 之后说」），
 * 第二次照犯。这就是**提示词的红线**：它能降低概率，给不了保证——
 * 而这里要的恰恰是保证，因为失败的样子是"用户什么都做不了"。
 *
 * 所以判据换成事实：**这一轮到底有没有真的把卡发出去**（[AiAgentLoop] 从工具返回的
 * `status == "awaiting_user_confirmation"` 记数，那是结构化的，不是话术）。
 * 说了卡、却一张都没发 → **不接受这句答复**，把它自己的话记回上下文，
 * 再补一条"你刚才没调用工具"的系统提醒，让它当场重做一次。
 *
 * ### 为什么是"重做"而不是"改写那句话"
 * 把「卡已发」改成「卡没发」只是把谎话变成一句正确的废话——用户要的是那两件事做成，
 * 不是知道卡没发。重做一次才是他真正想要的（而且模型这一步本来就该调 preview_write）。
 * 只有重做次数用尽时，才退回到"如实告诉他这次没成"。
 *
 * ### 判据为什么要"一词 + 一句"两个信号
 * 只认「确认卡」会把「要不要我发一张确认卡？」也判成谎话——那只是一句提问，
 * 白重做一轮（代价小但没必要）。所以要求**同时**出现：卡的字样 ＋ 表示"已经发出去了"的字样。
 */
internal object AiCardClaim {

    /** 提到"卡"的字样。只收会被用来指代确认卡的那几个词，不收单字"卡"（卡车、卡住都会误伤）。 */
    private val CARD_WORD = Regex("确认卡|卡片|张卡")

    /** 表示"已经发出去了／等你点"的字样。与 [CARD_WORD] **同时**命中才算谎话。 */
    private val CARD_SENT = Regex(
        "已发|已生成|已经发|发给你|发过去了|发好了|生成好|已提交|已送出|" +
            "请点|点一下|点击|去点|上面那张|等你确认|待你确认|等你点|在聊天页上",
    )

    /** 命中即认为"这句话在告诉用户去看一张卡"。 */
    fun looksLikeClaim(text: String): Boolean =
        text.lineSequence().any { line -> CARD_WORD.containsMatchIn(line) && CARD_SENT.containsMatchIn(line) }

    /**
     * 重做时喂回去的那一句（role=user）。
     *
     * 写成"事实 + 要求"，不写成道歉：模型上一轮已经读过提示词，
     * 再把提示词抄一遍没有用；有用的信息只有一个——**你刚才一次 preview_write 都没调用**。
     */
    const val NUDGE: String =
        "（系统提示）你上一条回复里说确认卡已经发给我了，**但你这一轮一次 preview_write 都没调用过**，" +
            "屏幕上没有任何卡可点，我这边什么都做不了。\n" +
            "请现在**真的调用 preview_write** 把刚才那几件事各申请一次卡；" +
            "如果确实做不到（工具报错、参数问不出来），就如实说清楚哪一件没做成、为什么。"

    /** 重做次数用尽后的纠正话术（此时已经不指望它再做一遍了，重点是别让用户干等）。 */
    const val EXHAUSTED: String =
        "⚠️ 我刚才说「确认卡发给你了」，但我其实没有申请任何卡——屏幕上没有卡可点。\n" +
            "请再回我一句「重做一次」，我马上重新申请；如果反复这样，请到「AI 助手设置」里换一个模型再试。"

    /**
     * 重做前先把屏幕上刚流出来的那句谎话**盖掉**（`replace = true`）。
     * 不盖的话，用户会先看到"卡已发"再看到真正的卡，仍然会去点不存在的那一张。
     */
    const val CORRECTION: String = "（我说错了——刚才那次我并没有真的把卡发出去，现在重新申请一次。）"
}
