package com.tapmoay.sorders.core

/**
 * 账号相关的**规定**——注意是"规定"，不是"某个可以随手改的默认参数"。
 *
 * ### 用户 2026-10-11 的原话（CHG-0118）
 * > 「我们的**所有账号初始密码默认是 123321**，这是**规定死的**。**AI 也要知道** ——
 * >   比如说我叫它创建一个账号，它**直接帮我创建好、不要问我密码是什么**；
 * >   当然也可以，它也可以问我"初始密码要按默认的走吗"。」
 *
 * ### 为什么要有这么一个文件（而不是各写各的）
 * 同一个数要出现在四个地方：后端建号 schema 的默认值、AI 动作的参数与卡片文案、
 * 提示词里那条"不要追问密码"、两个建号表单的初值。**手抄四份 = 迟早分叉**，
 * 而分叉的表现是"卡片上写着 123321、实际建出来的账号却是别的密码"——不报错、也没人发现，
 * 直到有人拿默认密码登不进去。所以：**每一边只有一处常量**，两侧由判据对账
 * （`_tools/qa/_check_default_password.py`）。
 *
 * ⛔ 这是"**初始**密码"：改密码（AI 的 `users.set_password`、编辑账号时填密码）
 *    **不适用**这条 —— 那里仍然必须由用户明确给出，没有"默认的新密码"这种东西。
 * ⛔ 与"本机开发库那三个测试号的登录口令恰好也是 123321"是**两件事**：那是环境事实
 *    （`docs/PROJECT_MAP/05_TESTING.md`），这是产品规定。别互相复用、也别互相引用。
 */
object AccountRules {

    /**
     * 所有账号的**初始密码**默认值。
     *
     * 后端同一份：`backend/app/core/security.py::DEFAULT_INITIAL_PASSWORD`
     * （判据 `_tools/qa/_check_default_password.py` 会核对两侧字符串一字不差）。
     */
    const val DEFAULT_INITIAL_PASSWORD = "123321"

    /**
     * 卡片 / 表单上写给人看的**那一句**（唯一一份，AI 卡片与表单说明同源）。
     *
     * 为什么必须写出来：用户口径是"AI 直接帮我创建好、不要问我密码"——那就必须让他
     * **看得见**这个账号的密码是什么，否则他只能靠猜（或者再问一遍 AI）。
     */
    const val DEFAULT_PASSWORD_NOTE =
        "将使用默认初始密码 " + DEFAULT_INITIAL_PASSWORD + "（你可以改）"

    /**
     * 建号抽屉里密码框的**初值**。
     *
     * @param isEdit true = 编辑既有账号 → 必须给**空串**：空串的语义是"不改密码"，
     *   预填默认值会把所有账号的密码**静默重置**成 123321（那是另一件事，不该在做"改个手机号"时发生）。
     */
    fun passwordDraft(isEdit: Boolean): String = if (isEdit) "" else DEFAULT_INITIAL_PASSWORD
}
