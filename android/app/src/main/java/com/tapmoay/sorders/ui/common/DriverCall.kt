package com.tapmoay.sorders.ui.common

import com.tapmoay.sorders.ui.nav.Role

/**
 * 「拨打司机电话」谁能用 —— **全 App 唯一一份判据**。
 *
 * ## 由来（用户 2026-09-22，两轮口述）
 * 第一轮：「加一个功能，就是在订单详情的界面当中**可以拨打司机电话**，这个功能显示
 * **只会在派单端里，其他人是没有的**」。
 *
 * 第二轮（本轮放宽）：「派单员，他是**可以拨打司机电话**的，包括啊或者**批发商也是可以拨打
 * 司机电话**的……他在那**详情页面**是有个选项的啊，拨打司机电话，**只有这两个人能看得到，
 * 司机是没有这个的**」。
 *
 * ## 口径
 * · **派单员** —— 这一行本来就是为他做的（"这单谁在拉、人到哪了"）；
 * · **批发商**（`is_member` 的货主）—— 他下的单是给他的下游客户的，司机到没到他要盯；
 * · ⛔ **普通货主不给**：用户只放开了批发商这一档，别顺手放宽成"所有货主"
 *   （这是放开一类权限，不是改个显示）；
 * · ⛔ **司机不给**：他不需要打给自己。
 *
 * ⚠️ 这里只决定**画不画那颗「拨号」按钮**。"司机是谁 + 电话"那一行本身三个角色都看得到
 * （它同时是"这单谁在拉"的记账信息），所以判据只落在动作上，不落在那一行上。
 */
fun canDialDriver(role: Role, memberShipper: Boolean): Boolean =
    role == Role.DISPATCHER || (role == Role.SHIPPER && memberShipper)
