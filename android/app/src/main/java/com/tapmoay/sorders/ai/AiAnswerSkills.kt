package com.tapmoay.sorders.ai

/**
 * **呈现技能**：回答里「这段信息该怎么排」由模型自己按**内容形状**选 —— 而不是一条业务场景一条业务场景地加规则。
 *
 * ### 用户口径（2026-10-09，ref m35395，语音转写）
 * - 「AI 的回答最好都要用表格的样式…上面有文字下面有信息混在一起就很难分辨出来，
 *   他具体想表达的核心内容是什么。」
 * - 「不要就是他啊就是搞一个我们来搞一个搞一个我们来搞一个，这样子太麻烦了」
 *   —— 别按场景一条条加规则，**让模型自己判断**要不要用表格。
 * - 「其实基本上只要涉及到信息的基本上他都要想啊想办法，比如说像表格呀，或者是其他的样式，
 *   把信息给表达出来。」
 *
 * ### 为什么写成「形状表」，而不是再加一条排版规则
 * [AiAnswerStyle] 第 9 条是按**触发条件**写的（条目超过 3 项就用表格）——条件之外它就不管了。
 * 用户那张截图正好落在条件外：三个字段 + 一句追问，模型写成了「• 标签：值」的散行，
 * 于是「值在哪、标签是哪个」只能一行行读（[AiAnswerShape] 兜的就是这一眼）。
 * 这里换一种写法：给**内容形状 → 排版**的对应表，模型自己认形状；以后加新场景不用动这张表。
 *
 * ### 为什么不是「每个模块配一套模板」
 * 用户在同一次里说过「特定的表格模板暂时也不需要搞…其实我们不给模板的话，其实 AI 做得更好」（ref m00779）。
 * 所以这里给的是**形状**（一组字段 / 多条记录 / 一条结论 / 要照做的步骤 / 要用户回答的问题），
 * ⛔ 不是按「商品」「订单」「账本」这些业务场景各配一套。
 *
 * ### 判据
 * `AiAnswerSkillsTest` 直接读这一份（和 [AiAnswerStyle] 同一规矩：提示词拼它、单测查它，同一份）。
 */
internal object AiAnswerSkills {

    /** 拼进 system prompt 的原文（[AiAgentLoop.systemPrompt] 接在 [AiAnswerStyle.RULES] 之后）。 */
    val RULES: String = buildString {
        appendLine("12. **按「内容形状」自己决定怎么排 —— 只要涉及信息，就让它一眼看清**（认形状，⛔ 不是按业务场景套模板）：")
        appendLine("   - 一个对象的一组字段（收货人 / 电话 / 地址）→ **两列表**「标签 | 值」，一行一个字段。")
        appendLine("     ⛔ 不要写成「• 标签：值」的散行 —— 那正是用户说的「上面有文字下面有信息混在一起」，值在哪要靠猜。")
        appendLine("   - 多条同类记录（商品、订单、司机、流水、账目）→ **多列表格**，第一行写列名，最多 4 列；列多就拆成两张表。")
        appendLine("   - 一条结论 + 几条依据 → **第一行先给结论**（一句话），要摆数据再接着表格或分行。")
        appendLine("   - 让用户照做的步骤（有先后）→ **编号列表**，一行一步，动词开头。")
        appendLine("   - 要用户回答的问题 → **单独一行、放在最后**；⛔ 不要塞进字段行里，也不要和上面那段信息连成一句。")
        appendLine("   - 一句话就能说完的（「这单已送达」「查不到」）→ 直接说，⛔ 不要为了排版硬凑一张表。")
        appendLine("   第 9 条那个「超过 3 项」是**下限不是门槛**：只要有 ≥2 行同类信息（哪怕只有两行「标签：值」），就该排开。")
        appendLine("   表格写法：用 Markdown 表格（界面会画成真表格，数字自动对齐），单元格里只放短语 —— 一整句话别塞进去；")
        appendLine("   ⛔ 不要用竖线手搓 ASCII 边框、⛔ 不要写「如下表所示」这类空话；某个值没有就写「—」，那一行不要省。")
        appendLine("   ⛔ 不要为了凑表格编内容：没查到就直说没查到。")
    }
}
