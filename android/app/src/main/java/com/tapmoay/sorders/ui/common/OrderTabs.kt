package com.tapmoay.sorders.ui.common

/**
 * 订单列表顶栏那一排状态档位中的一档（派单员「订单管理」与货主「我的订单」**共用这一个模型**）。
 *
 * @param key 后端 `GET /orders?status=` 的取值；`null` = 「全部」（不带状态条件）
 * @param label 顶栏上显示的中文
 * @param dated 这一档**按日期筛**：顶栏右上角那颗药丸**可点**（点开是档位清单 + 自定义区间），
 *        列表带上日期条件。
 * @param windowWord 这一档**不按日期筛**，但为了顶栏形态统一，也画一颗**不可点**的药丸、
 *        上面写这个词（给「派单中」「已接单」用）。用户 2026-09-22 第三轮原话：
 *        「为了美观而统一…给那个**已接单**和**派单中**也加一个图标，但是那个图标**无法选择**，
 *        他不会有列表，就是只有显示…就是也说这个信息提醒吧」。
 *        ⛔ **不许写日期档位名**（「今天」「昨天」…）：那两档的列表**不按日期筛**，
 *        写「今天」就会出现"一张 09-11 的单挂在「今天」下面"—— 屏幕上的一句假话
 *        （本机实测：派单中 7 单跨 09-16~09-21、已接单 8 单跨 09-11~09-20）。
 *        判据 `_tools/qa/_check_order_list_ui.py` 拿 `DatePresets.ROW` 逐个核这个词。
 *
 * ## 为什么这些标记挂在**档位自己**身上，而不是在页面里写下标（2026-09-22）
 *
 * 原来两个页面都是拿**下标**判的：`if (selectedTab == 3 || selectedTab == 4)`。
 * 这种写法在档位顺序被改动时**不会报错**，只会静默错位 —— 本轮把货主那列的「已接单」
 * 从第 3 格挪到第 2 格（用户要求"往前一格排第 2 位置"），恰好没碰到 3/4；
 * 下一次谁再挪一格，时间窗口就会挂到一个毫不相干的档位上：比如「全部」被按"今天"过滤，
 * 用户看到的是"单丢了"，而代码里一个字都没变红。
 *
 * 所以"这一档有没有窗口、窗口能不能点"跟着**档位自己**走，跟下标无关。
 * 判据：`_tools/qa/_check_order_list_ui.py`（不许再出现 `== 3 || == 4` 这种下标判据）。
 */
data class OrderTab(
    val key: String?,
    val label: String,
    val dated: Boolean = false,
    val windowWord: String? = null,
)

/**
 * 「正在进行」那两档（派单中 / 已接单）那颗**不可点**药丸上写的词。
 *
 * ⛔ 为什么不是「今天」（用户口述里说的是"只显示今天"）：那两档的列表**不按日期筛**，
 * 里面放的是**所有**未完成的单。本机实测：派单中 7 单跨 09-16~09-21、已接单 8 单跨
 * 09-11~09-20 —— 药丸上写「今天」，就会出现"一张 09-11 的单挂在「今天」下面"，
 * 而用户没有办法点开它去发现这一点（这颗药丸**故意不可点**）。
 * 本仓库的规矩是「数字/口径词必须跟着**实际**窗口走」，所以这里写的是**实话**：
 * 这一档不限时间。形态与另外几档完全一样（同一个组件、同一个位置、同一个圆角与配色），
 * 差别只有两个：**没有 ▾ 箭头**（不邀请用户去点一个点了没反应的东西）、**点不开**。
 */
const val ORDER_WINDOW_NO_LIMIT_WORD = "不限时间"

/**
 * 服务端 `GET /orders` 的缺省条数上限，与后端 `DEFAULT_LIST_LIMIT` 对齐（300）。
 *
 * 原来派单员与货主两个 ViewModel **各写了一份**（连同"与后端对齐"那句注释）：
 * 数值要改时必然只改一处，而两边的表现会是"同一个后端、两个页面的截断点不一样"。
 * 现在只有这一份，两个页面都用它判"这一页可能不是全部"。
 *
 * ⚠️ 判据是**推出来的**（`orders.size >= ORDER_LIST_LIMIT`），不是响应头 —— 订单列表走的是
 *    `GET /orders` 的 `limit` 路径，页面上要不要换成读 `X-Truncated`（`pageMeta()`）是另一件事，
 *    换的时候**三处一起换**（两个 VM + 这一行的注释）。
 */
const val ORDER_LIST_LIMIT = 300

/**
 * 列表被截断时，那句「还能怎么看到更早的」 —— **两个订单列表共用这一句**。
 *
 * 用户 2026-09-22 把这条提示从顶部挪到列表最后一行（「这个提示删掉啊，**他占位置了**」），
 * 两个页面都要说同一件事。⛔ 别在两页各写一份：这句话里点名的入口（右上角的日期筛选、
 * 哪几档才有）**以后一定会变** —— 那时改一处漏一处，用户按提示去找会找不到。
 * ⚠️ 措辞必须点名一个**页面上真实存在**的入口（`_check_page_truncation_wiring.py` 的规矩）。
 */
const val ORDER_TRUNCATION_HOW = "要按时间找，用右上角的日期筛选（切到「已送达」或「已撤销」才会出现）"
